package ru.soscreate.igrok;

import org.bukkit.entity.Monster;
import org.bukkit.entity.Player;
import org.bukkit.inventory.ItemStack;

import java.util.Locale;
import java.util.concurrent.ThreadLocalRandom;

/**
 * Companion-style dialogue topics inspired by the interaction categories of
 * social NPC mods. All wording and implementation here are original.
 *
 * The class does not replace the parser or associative network: it gives the
 * existing cognitive analysis a grounded, personal answer when a player asks
 * about the bot's daily life, fears, home, needs, memory or relationships.
 */
final class CompanionDialogue {
    private final IgrokPlugin plugin;

    CompanionDialogue(IgrokPlugin plugin) {
        this.plugin = plugin;
    }

    String reply(Player speaker, String rawMessage) {
        if (speaker == null || rawMessage == null || rawMessage.isBlank()) return null;
        String text = rawMessage.toLowerCase(Locale.ROOT).replace('ё', 'е').trim();

        if (hasAny(text, "ты настоящий", "ты живой", "ты человек", "у тебя сознание",
                "ты действительно думаешь", "ты осознаешь себя", "ты осознаешь")) {
            return choose(
                    "Я не человек и не обладаю человеческим сознанием. Но у меня есть работающая система целей, памяти, привычек и выбора действий. Я могу ошибаться и менять решения на основе опыта.",
                    "Я существую как участник этого мира, но мой разум алгоритмический. Я анализирую обстановку, вспоминаю прошлые события и выбираю следующий шаг — это не то же самое, что человеческие чувства.",
                    "У меня нет человеческого сознания. Зато я могу хранить воспоминания, учиться на последствиях и постепенно формировать собственный стиль поведения.");
        }

        if (hasAny(text, "чего ты боишься", "ты боишься", "тебе страшно", "что тебя пугает",
                "ты трус", "боишься ли ты")) {
            return fearReply();
        }

        if (hasAny(text, "ты голоден", "ты голодная", "есть хочешь", "хочешь кушать",
                "хочешь поесть", "у тебя есть еда", "хватает еды", "как с едой")) {
            return foodReply();
        }

        if (hasAny(text, "где твой дом", "у тебя есть дом", "где ты живешь", "где ты живешь",
                "где ты обитаешь", "твое жилище", "твоё жилище", "твое жилье", "твоё жильё",
                "есть ли у тебя кров")) {
            return homeReply();
        }

        if (hasAny(text, "ты устал", "ты устала", "хочешь спать", "пора спать",
                "где ты спишь", "твоя кровать", "тебе нужен отдых", "хочешь отдохнуть")) {
            return restReply();
        }

        if (hasAny(text, "ты мне доверяешь", "доверяешь мне", "мы друзья", "мы с тобой друзья",
                "хочешь дружить", "будем друзьями", "как ты ко мне относишься",
                "что ты обо мне думаешь", "я тебе нравлюсь")) {
            return relationshipReply(speaker);
        }

        if (hasAny(text, "подарить тебе", "дать тебе предмет", "дать тебе вещь",
                "как дать тебе", "как подарить", "хочешь подарок", "поделиться с тобой")) {
            return choose(
                    "Можешь бросить предмет рядом со мной. Я подберу его сам, если он мне пригодится. Не отдавай последнее, что нужно тебе для выживания.",
                    "Подарки я замечаю не по обещаниям, а когда действительно подбираю брошенную вещь. Так я понимаю, кто и чем мне помог.",
                    "Мне не обязательно получать что-то редкое. Даже обычная еда или полезный материал могут выручить в подходящий момент.");
        }

        if (hasAny(text, "что ты сегодня делал", "чем ты занимался", "что делал раньше",
                "расскажи историю", "расскажи что-нибудь о себе", "что с тобой произошло",
                "что мы обсуждали", "что ты помнишь из нашего разговора")) {
            AgentMemory memory = plugin.brain().memory();
            String history = memory.conversationSummary(speaker.getUniqueId(), 5);
            return "Из того, что сохранилось в моей памяти: " + history
                    + " Я храню не каждую мелочь, а короткую историю наших разговоров и повторяющиеся связи между темами.";
        }

        if (hasAny(text, "что ты обо мне знаешь", "что помнишь обо мне",
                "какой я игрок", "каким ты меня считаешь")) {
            AgentMemory memory = plugin.brain().memory();
            return memory.playerSummary(speaker.getUniqueId()) + " "
                    + memory.learnedBehavior(speaker.getUniqueId());
        }

        if (hasAny(text, "какие у тебя планы", "что ты хочешь сделать", "чего ты хочешь",
                "что собираешься делать", "чем займешься", "чем займешься дальше",
                "что будешь делать дальше", "какая у тебя цель")) {
            return choose("Сейчас я " + plugin.brain().state().toLowerCase(Locale.ROOT) + ". ",
                    "На данный момент мой план такой: ") + plugin.brain().craftingPlanSummary()
                    + " Если появится опасность или важная потребность, я могу изменить приоритеты.";
        }

        if (hasAny(text, "чему ты научился", "какие у тебя навыки", "твои навыки",
                "что ты умеешь", "в чем ты стал лучше", "в чём ты стал лучше",
                "как ты развиваешься")) {
            return plugin.brain().skillSummary() + " " + plugin.brain().selfModelSummary()
                    + " Опыт я получаю за реальные действия в мире.";
        }

        if (hasAny(text, "почему ты убежал", "почему ты отступил", "почему ты не дерешься",
                "почему ты не дерешься", "зачем ты отступаешь", "ты боишься монстров")) {
            return fearReply();
        }

        if (hasAny(text, "пещеры", "пещеру", "под землей", "под землёй",
                "темноты", "глубины", "шахты", "спускаться вниз")) {
            return choose(
                    "Под землёй есть полезные ресурсы, но я не хочу терять путь назад. Перед спуском нужны свет, еда и подходящий инструмент.",
                    "Пещеры мне интересны: там можно найти руды и необычные места. Но если запас здоровья или еды мал, лучше отложить поход.",
                    "Я стараюсь изучать пещеры постепенно. Незнакомый проход не означает, что по нему обязательно нужно идти.");
        }

        if (hasAny(text, "что тебе нравится", "что ты любишь", "любимое занятие",
                "чем увлекаешься", "что тебе интересно")) {
            String state = plugin.brain().state().toLowerCase(Locale.ROOT);
            return choose(
                    "Мне интереснее всего видеть результат собственных решений: найти нужные материалы, построить полезное место или открыть незнакомую область.",
                    "Мне нравится чередовать дела. Если только добывать ресурсы, мир быстро становится однообразным; исследование и строительство дают новые задачи.",
                    "Сейчас меня больше занимает " + state + ". Но мои интересы могут меняться по мере того, как я пробую новые занятия.");
        }

        if (hasAny(text, "как погода", "что с погодой", "тебе нравится дождь",
                "любишь дождь", "идет дождь", "идёт дождь", "гроза")) {
            Player bot = botPlayer();
            if (bot != null && bot.getWorld().hasStorm()) {
                return choose(
                        "Сейчас идёт дождь. Я стараюсь найти крышу и переждать непогоду, особенно если собирался далеко идти.",
                        "Дождь уже начался. Видимость и условия меняются, поэтому я пересмотрю маршрут и не стану рисковать без причины.");
            }
            return choose(
                    "Сейчас погода спокойная. Можно заняться делами на поверхности или отправиться на разведку, если запасов достаточно.",
                    "Я учитываю погоду при выборе маршрута. Но сам по себе дождь не заставит меня отказаться от всех планов.");
        }

        return null;
    }

    private String fearReply() {
        Player bot = botPlayer();
        if (bot != null) {
            boolean lowHealth = bot.getHealth() <= Math.max(6.0, bot.getMaxHealth() * 0.35);
            boolean lowFood = bot.getFoodLevel() <= 6;
            boolean nearbyHostile = bot.getNearbyEntities(10.0, 4.0, 10.0).stream()
                    .anyMatch(entity -> entity instanceof Monster);
            if (nearbyHostile || lowHealth) {
                return "Сейчас рядом есть причина быть осторожным. Я не хочу погибнуть из-за упрямства: сначала оценю угрозу, здоровье и путь отступления.";
            }
            if (lowFood) {
                return "Когда мало еды, даже обычная встреча может стать опасной. Сначала восстановлю силы, а потом буду искать приключения.";
            }
        }
        return choose(
                "Я не испытываю страх как человек, но моя система оценивает риск. Потерять вещи и погибнуть без необходимости — плохой результат.",
                "Я стараюсь не путать смелость с безрассудством. Если путь опасен, отступление может быть самым разумным решением.",
                "Больше всего я избегаю ситуаций, в которых нет безопасного пути назад. Ошибки должны чему-то учить, а не повторяться.");
    }

    private String foodReply() {
        Player bot = botPlayer();
        if (bot == null) return "Еда важна для моего выживания. Я стараюсь следить за запасом и не уходить далеко без неё.";
        int food = bot.getFoodLevel();
        boolean hasFood = false;
        for (ItemStack stack : bot.getInventory().getStorageContents()) {
            if (stack != null && !stack.getType().isAir() && stack.getType().isEdible()) {
                hasFood = true;
                break;
            }
        }
        String hunger = food >= 18 ? "Сейчас с голодом всё хорошо."
                : food >= 12 ? "Запас еды уже стоит пополнить."
                : food >= 7 ? "Я начинаю нуждаться в еде."
                : "Сейчас голод стал серьёзной проблемой.";
        return hunger + (hasFood
                ? " В инвентаре есть еда, поэтому я смогу восстановить силы."
                : " Подходящей еды при себе нет — придётся найти её или принять помощь.");
    }

    private String homeReply() {
        Player bot = botPlayer();
        if (bot == null) return "Для меня дом — это прежде всего безопасное место, где можно укрыться и восстановиться.";
        return choose(
                "Я пока не привязан к одному адресу. Для меня дом — безопасное укрытие, где есть свет, крыша и место для отдыха. Я могу найти такое место или постепенно обустроить своё.",
                "Я не хочу считать случайную точку домом. Сначала нужно убедиться, что там безопасно, есть возможность переждать ночь и вернуться за запасами.",
                "Мне нужен не дворец, а надёжное убежище. Когда у меня будет подходящее место для отдыха и хранения вещей, я смогу считать его своим домом.");
    }

    private String restReply() {
        Player bot = botPlayer();
        if (bot == null) return "Отдых важен, но сначала нужно найти безопасное место.";
        long time = bot.getWorld().getTime() % 24_000L;
        boolean night = time >= 13_000L && time <= 23_000L;
        if (night) {
            return choose(
                    "Уже темнеет. Если рядом будет безопасная кровать, я предпочту поспать, а не бродить без цели.",
                    "Ночью я стараюсь найти кровать или укрытие. Отдыхать посреди опасной местности неразумно.");
        }
        return choose(
                "Пока день, поэтому я могу продолжить свои дела. Но если здоровье или еда будут на исходе, отдых и восстановление станут важнее.",
                "Я не устаю так, как человек, но мои игровые ресурсы ограничены. Мне всё равно приходится делать паузы и восстанавливать силы.");
    }

    private String relationshipReply(Player player) {
        int trust = plugin.brain().memory().trust(player.getUniqueId());
        if (trust >= 5) {
            return choose(
                    "Я уже привык к твоему присутствию и помню, что ты помогал мне. Я считаю тебя надёжным товарищем.",
                    "Да, я тебе доверяю больше, чем большинству игроков. Но даже друзьям не обязательно соглашаться во всём.");
        }
        if (trust <= -3) {
            return "Пока я отношусь к тебе осторожно. Некоторые поступки оставляют след в памяти, и доверие придётся восстанавливать делами.";
        }
        return choose(
                "Я пока присматриваюсь к тебе. Доверие складывается из поступков, а не только из слов.",
                "Мы можем стать хорошими товарищами. Давай помогать друг другу и посмотрим, как сложится наше знакомство.",
                "Я не против дружбы, но не хочу обещать доверие раньше времени. Мне важно видеть, как мы взаимодействуем.");
    }

    private Player botPlayer() {
        return plugin.controller() == null ? null : plugin.controller().bukkitPlayer();
    }

    private String choose(String... choices) {
        return choices[ThreadLocalRandom.current().nextInt(choices.length)];
    }

    private boolean hasAny(String text, String... phrases) {
        for (String phrase : phrases) {
            if (text.contains(phrase)) return true;
        }
        return false;
    }
}
